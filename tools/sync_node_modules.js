const fs = require('fs');
const path = require('path');

const srcNodeModules = 'd:/RA_SEBI_COMPLINCE/frontend/node_modules';
const destNodeModules = 'd:/RA_SEBI_COMPLINCE/frontend_vit/node_modules';

const srcList = fs.readdirSync(srcNodeModules);
let copied = 0;

srcList.forEach(item => {
  if (item === '.bin' || item === '.package-lock.json' || item.startsWith('.')) return;

  const srcItemPath = path.join(srcNodeModules, item);
  const destItemPath = path.join(destNodeModules, item);

  if (item.startsWith('@')) {
    // scoped package
    if (!fs.existsSync(destItemPath)) {
      fs.mkdirSync(destItemPath, { recursive: true });
    }
    const scopedList = fs.readdirSync(srcItemPath);
    scopedList.forEach(scopedItem => {
      const srcSub = path.join(srcItemPath, scopedItem);
      const destSub = path.join(destItemPath, scopedItem);
      if (!fs.existsSync(destSub)) {
        try {
          fs.cpSync(srcSub, destSub, { recursive: true });
          copied++;
        } catch (e) {
          console.error(`Failed copying ${item}/${scopedItem}:`, e.message);
        }
      }
    });
  } else {
    if (!fs.existsSync(destItemPath)) {
      try {
        fs.cpSync(srcItemPath, destItemPath, { recursive: true });
        copied++;
      } catch (e) {
        console.error(`Failed copying ${item}:`, e.message);
      }
    }
  }
});

console.log(`Copied ${copied} missing packages from frontend/node_modules to frontend_vit/node_modules!`);
